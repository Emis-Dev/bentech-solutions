import assert from 'node:assert/strict';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base=process.env.BENTECH_QA_URL||'http://127.0.0.1:8788';
const out=process.env.BENTECH_QA_OUT||'.impeccable/review';
await mkdir(out,{recursive:true});
const browser=await chromium.launch({headless:true,channel:'chrome',args:['--disable-external-intent-requests-for-testing']});
const report={base,states:[],errors:[]};
try{
 const context=await browser.newContext();
 const page=await context.newPage();
 page.on('pageerror',e=>report.errors.push(String(e)));
 const google=[];
 await context.route(/googletagmanager\.com|google-analytics\.com|googleadservices\.com/,route=>{google.push(route.request().url());route.fulfill({status:200,contentType:'text/javascript',body:'/* mocked analytics: no data transmitted */'});});
 await page.setViewportSize({width:1440,height:1000});
 await page.goto(base,{waitUntil:'networkidle'});
 assert.equal(google.length,0,'No Google request before consent');
 assert.equal(await page.locator('#marketingConsentBanner').isVisible(),true);
 await page.screenshot({path:`${out}/consent-desktop.png`,fullPage:false});
 await page.click('#rejectMarketingConsent');
 assert.equal(await page.locator('html').getAttribute('data-marketing-consent'),'denied');
 for (const [width,height,name] of [[1440,1000,'desktop'],[1024,900,'tablet'],[390,844,'mobile'],[320,720,'mobile-320']]){
  await page.setViewportSize({width,height});
  await page.goto(base,{waitUntil:'networkidle'});
  await page.evaluate(()=>document.fonts.ready);
  await page.waitForTimeout(1600);
  const metrics=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth,images:[...document.images].every(i=>i.complete&&i.naturalWidth>0),font:document.fonts.check('800 20px Manrope'),h1:document.querySelectorAll('h1').length}));
  assert.ok(metrics.scroll<=width,`overflow at ${width}: ${metrics.scroll}`);
  assert.ok(metrics.images,`image load ${width}`);assert.ok(metrics.font,'Manrope loaded');assert.equal(metrics.h1,1);
  await page.screenshot({path:`${out}/${name}.png`,fullPage:true});
  report.states.push({name,...metrics});
  if(width<993){
   await page.click('#mobileToggle');assert.equal(await page.locator('#mobileToggle').getAttribute('aria-expanded'),'true');
   await page.screenshot({path:`${out}/${name}-menu.png`});
   await page.keyboard.press('Escape');assert.equal(await page.locator('#mobileToggle').getAttribute('aria-expanded'),'false');
   assert.equal(await page.locator('#mobileToggle').evaluate(e=>e===document.activeElement),true);
  }
  await page.locator('[data-service-choice="LOGO!-domotica"]').click();
  assert.equal(await page.locator('#offerte').getAttribute('open'),'');
  assert.equal(await page.locator('#q-service').inputValue(),'LOGO!-domotica');
  await page.locator('button[data-channel="server"]').click();
  assert.equal(await page.locator('.form-handoff-status').count(),0,'Invalid form must not hand off');
  await page.locator('#q-name').fill('QA & <voorbeeld>');
  await page.locator('#q-email').fill('qa@example.invalid');
  await page.locator('#q-details').fill('Test: pomp schakelen bij niveau > 5. Geen externe verzending.');
  await page.evaluate(()=>{window.__handoffs=[];window.open=(...args)=>{window.__handoffs.push(args);return null;};});
  await page.locator('a[data-channel="whatsapp"]').click();
  const links=await page.locator('.form-handoff-status a').evaluateAll(a=>a.map(e=>e.href));
  assert.match(links[0],/^https:\/\/wa.me\/32486328645\?text=/);
  const payload=new URL(links[0]).searchParams.get('text');
  assert.ok(payload.includes('LOGO!-domotica')&&payload.includes('QA & <voorbeeld>'));
  assert.match(links[1],/^mailto:info@bentechsolutions.be\?subject=/);
  const email=new URL(links[1]);assert.ok(email.searchParams.get('body').includes('niveau > 5'));
  assert.equal(await page.evaluate(()=>window.__handoffs.length),1);
  assert.match(await page.locator('.form-handoff-status').innerText(),/nog niet ontvangen/);
  await page.locator('.form-handoff-status').scrollIntoViewIfNeeded();
  await page.evaluate(()=>scrollTo(0,0));
  await page.waitForTimeout(500);
  await page.screenshot({path:`${out}/${name}-form.png`,fullPage:true});
  report.states.push({name:`${name}-form`,valid:true,externalSends:0});
 }
 await page.setViewportSize({width:390,height:844});
 await page.goto(base,{waitUntil:'networkidle'});
 await page.click('#manageMarketingConsent');
 await page.screenshot({path:`${out}/consent-mobile.png`});
 await page.click('#acceptMarketingConsent');
 assert.equal(google.length,1,'One Google tag after granting consent');
 assert.equal(await page.locator('html').getAttribute('data-marketing-consent'),'granted');
 const tags=await page.evaluate(()=>window.dataLayer.map(x=>Array.from(x)));
 assert.equal(tags[0][0],'consent');assert.equal(tags[0][2].ad_storage,'denied');
 await page.click('#manageMarketingConsent');await page.click('#rejectMarketingConsent');await page.waitForLoadState('networkidle');
 assert.equal(await page.locator('html').getAttribute('data-marketing-consent'),'denied');
 assert.equal(google.length,1,'Revocation reload must not load Google');
 await page.emulateMedia({reducedMotion:'reduce'});await page.goto(base);
 assert.equal(await page.locator('.hero-picture').evaluate(e=>getComputedStyle(e).animationName),'none');
 for(const path of ['/privacy/','/does-not-exist/']){
  const response=await page.goto(base+path,{waitUntil:'networkidle'});
  assert.equal(response.status(),path.includes('does-not')?404:200);
  assert.ok(await page.locator('h1').innerText());
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:`${out}/${path.includes('privacy')?'privacy':'404'}-mobile.png`,fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  assert.equal(await page.locator('.nav-quote use').getAttribute('href'),'#i-arrow');
  assert.equal(await page.locator('#i-arrow').count(),1);
  await page.screenshot({path:`${out}/${path.includes('privacy')?'privacy':'404'}-desktop.png`,fullPage:true});
  await page.setViewportSize({width:390,height:844});
 }
 const noScript=await browser.newContext({javaScriptEnabled:false,viewport:{width:390,height:844}});
 const fallback=await noScript.newPage();
 await fallback.goto(base);
 await fallback.locator('#offerte summary').click();
 assert.equal(await fallback.locator('#q-name').isEnabled(),true);
 assert.equal(await fallback.locator('button[data-channel="server"]').isEnabled(),true);
 assert.equal(await fallback.locator('noscript').isVisible(),true);
 assert.equal(await fallback.locator('#quoteForm').getAttribute('method'),'post');
 assert.ok(await fallback.locator('a[href="mailto:info@bentechsolutions.be"]').count());
 await fallback.evaluate(()=>scrollTo(0,0));
 await fallback.screenshot({path:`${out}/no-script-mobile.png`,fullPage:true});
 await noScript.close();
 report.noScript={nativePostEnabled:true,directContactAvailable:true,noPersonalDataInURL:true};
 assert.equal(report.errors.length,0,JSON.stringify(report.errors));
 report.consent={defaultBlocked:true,refusal:true,grant:true,revocation:true,googleRequestsMocked:google.length};
 await writeFile(`${out}/browser-qa.json`,JSON.stringify(report,null,2));
 console.log(JSON.stringify(report,null,2));
}finally{await browser.close();}
